using System;
using System.Security.Cryptography;

namespace CodeDesigner.Ps2.Multiplayer.Dnas;

/// <summary>Inputs the original service must generate/choose. Unknown checks have no fabricated defaults.</summary>

public sealed partial class Server
{
    /// <summary>Generates all 328 reply bytes from supplied challenge/signing data; never loads replay templates.</summary>
    public byte[] BuildResponse(byte[] initialRequest308, FirstResponseData content)
    {
        if (content == null) throw new ArgumentNullException(nameof(content));
        // The stock client independently validates the signed type-1 operand
        // with its fixed retail trust anchor. A lab-generated signing key
        // must never masquerade as a compatible first server response.
        // The retail client verifies the original RSA signature with its own public key.
        // A title modulus is optional for server-side diagnostics, not response generation.
        if (content.RsaModulus128 != null) RSA.VerifyServerOperand(content.RsaOperand128, content.RsaModulus128);
        Packet initial = new Packet(initialRequest308);
        Guard.Operation(initial, Public.ClientConnect, 268);
        byte[] body = new byte[288];
        Buffer.BlockCopy(content.Challenge8A, 0, body, 0, 8);
        Buffer.BlockCopy(content.DesCiphertext16, 0, body, 8, 16);
        Buffer.BlockCopy(content.Challenge8B, 0, body, 24, 8);
        Buffer.BlockCopy(content.RsaOperand128, 0, body, 32, 128);
        Buffer.BlockCopy(content.Nested32, 0, body, 160, 32);
        Buffer.BlockCopy(content.Tail96, 0, body, 192, 96);
        Packet plain = Packet.Make(content.ResponseHeader40, Public.ServerConnect, body);
        return Protocol.EncryptReply1(initial, plain).Raw;
    }

    /// <summary>
    /// Verify the authentic 184-byte PS2 client response to a previously issued
    /// 328-byte first server challenge. The actual eight-byte Challenge A selects
    /// three signed-image SHA-1 ranges for the original client DES key. The RSA
    /// portion uses the retail client's original public operation. It does NOT use a
    /// captured request, an HMAC substitution, or a guessed success flag.
    ///
    /// The caller must associate firstReply328 with the exact issued challenge
    /// in its own authenticated server-side session state. The embedded RSA
    /// operand must have been signed by the matching original authority;
    /// this routine cannot create that signature.
    /// </summary>
    public bool VerifyClientProof(byte[] firstReply328, byte[] clientRequest184, byte[]? rsaModulus128 = null)
    {
        Packet outer = Protocol.DecryptReply1Outer(new Packet(firstReply328));
        byte[] challengeA = outer.Payload.AsSpan(0, 8).ToArray();
        return VerifyClientProofWithDerivedKey(firstReply328, clientRequest184, ImageIndependentChallenge.DeriveKey(challengeA), rsaModulus128);
    }

    /// <summary>
    /// Verifier with explicit DES key for fixture research and standalone tests.
    /// The normal live verifier derives the known empty-range key from S1 A
    /// and never accepts caller-supplied image-dependent keys.
    /// </summary>
    public bool VerifyClientProofWithDerivedKey(byte[] firstReply328, byte[] clientRequest184, byte[] derivedKey8, byte[]? rsaModulus128 = null)
    {
        Guard.Size(derivedKey8, 8, nameof(derivedKey8));
        Packet challenge = new Packet(firstReply328);
        Packet response = new Packet(clientRequest184);
        Guard.Operation(challenge, Public.ServerConnect, 288);
        Guard.Operation(response, Public.ClientProof, 144);
        Guard.SameSession(challenge, response);
        // The client decrypts the DES challenge and independently unwraps the
        // signed RSA operand using the title's public modulus built into the game.
        // The server does not need that public modulus to issue or answer S1.
        Packet outer = Protocol.DecryptReply1Outer(challenge);
        byte[] expectedPrefix = Protocol.FirstReplyPrefix(outer, derivedKey8);
        bool valid = CryptographicOperations.FixedTimeEquals(response.Payload.AsSpan(0, 16), expectedPrefix);
        valid &= CryptographicOperations.FixedTimeEquals(response.Payload.AsSpan(133, 11), new byte[11]);

        // When a separately supplied modulus exists, also check the returned
        // 117-byte RSA payload. Without it, this comparison is unavailable;
        // only the issuing client can perform the RSA public operation.
        if (rsaModulus128 != null)
        {
            byte[] expected117 = RSA.VerifyServerOperand(outer.Payload.AsSpan(32, 128).ToArray(), rsaModulus128);
            valid &= CryptographicOperations.FixedTimeEquals(response.Payload.AsSpan(16, 117), expected117);
        }

        return valid;
    }

    /// <summary>Emits the known second reply framing; the 128-byte result MUST be generated by caller logic.</summary>
    public byte[] BuildResponse(byte[] clientRequest184, byte[] produced128)
    {
        Packet incoming = new Packet(clientRequest184);
        Guard.Operation(incoming, Public.ClientProof, 144);
        Guard.Size(produced128, 128, nameof(produced128));
        byte[] body = new byte[130];
        body[0] = 2;
        body[1] = 1;
        Buffer.BlockCopy(produced128, 0, body, 2, 128);
        return Packet.Make(incoming.Header, Public.ServerProof, body).Raw;
    }

    /// <summary>Final reply packet assembly; a successful status is NOT inferred from framing alone.</summary>
    public byte[] BuildResponse(byte[] finalClientRequest44, byte flag, byte[] result32)
    {
        Packet incoming = new Packet(finalClientRequest44);
        Guard.Operation(incoming, Public.ClientFinal, 4);
        // The four C3 body bytes vary between original patched/unpatched retail
        // clients. Their historical backend meaning remains unmapped; the
        // native protocol framing and session checks are enforced elsewhere.
        Guard.Size(result32, 32, nameof(result32));
        byte[] body = new byte[37];
        body[0] = flag;
        body[4] = 32;
        Buffer.BlockCopy(result32, 0, body, 5, 32);
        return Packet.Make(incoming.Header, Public.ServerFinal, body).Raw;
    }

    public UnwrappedInitial InspectInitialClientProof(byte[] request308)
        => Protocol.InspectInitialPacket(new Packet(request308));

    /// <summary>
    /// Validate the recovered inverse of the four original shared-core proof
    /// calculations against the expected console/disc/title inputs. A/B/C/D
    /// materials are supplied in EXECUTION order; the packet stores A/B/D/C.
    /// The original server policy, unknown runtime material and RSA authority
    /// are separate requirements. A true return value is not authorization.
    /// </summary>
    public bool VerifyInitialNativeProofs(byte[] request308, ProofInputPlan identity, NativeProofCore.Material[] materials, byte nativeParameter = 2)
    {
        if (identity == null) throw new ArgumentNullException(nameof(identity));
        if (materials == null || materials.Length != 4) throw new ArgumentException("Four original native caller-material banks required.", nameof(materials));
        UnwrappedInitial evidence = InspectInitialClientProof(request308);
        if (!evidence.ZeroPaddingValid || !evidence.FixedTrailerValid) return false;
        byte[][] actual = { evidence.Fields.A40, evidence.Fields.B56, evidence.Fields.Disc32, evidence.Fields.Serial40 };
        byte[][] expected = identity.InputOrder();
        bool valid = true;
        for (int i = 0; i < 4; i++) valid &= NativeProofDecoder.VerifyIdentity(actual[i], expected[i], nativeParameter, materials[i]);
        return valid;
    }

    /// <summary>
    /// Strengthens the identity inverse with the original per-stage RNG stream.
    /// This overload is only appropriate when the native entry state and lack
    /// of inter-stage draws are established by independent runtime evidence.
    /// A true result is a calculation check, NOT backend authorization.
    /// </summary>
    public bool VerifyInitialNativeProofsWithRng(byte[] request308, ProofInputPlan identity, NativeProofCore.Material[] materials, ulong nativeEntryState, byte nativeParameter = 2)
    {
        if (!VerifyInitialNativeProofs(request308, identity, materials, nativeParameter)) return false;
        UnwrappedInitial result = InspectInitialClientProof(request308);
        return NativeProofDecoder.VerifySequentialRng(result.Fields, materials, nativeEntryState, nativeParameter);
    }

    /// <summary>
    /// As with VerifyInitialNativeProofsWithRng, this is an independent
    /// mathematical check rather than the original server's authorization
    /// policy. The schedule must be supported by original caller evidence.
    /// </summary>
    public bool VerifyInitialNativeProofsWithSchedule(byte[] request308, ProofInputPlan identity, NativeProofCore.Material[] materials, ulong nativeEntryState, NativeProofDrawSchedule schedule, byte nativeParameter = 2)
    {
        if (!VerifyInitialNativeProofs(request308, identity, materials, nativeParameter)) return false;
        UnwrappedInitial result = InspectInitialClientProof(request308);
        return NativeProofDecoder.VerifyScheduledRng(result.Fields, materials, nativeEntryState, schedule, nativeParameter);
    }

    /// <summary>
    /// Structural integrity of the original decrypted 256-byte envelope ONLY.
    /// A valid zero region and trailer do not authenticate any of the four
    /// opaque identity proofs, and must never authorize the next protocol step.
    /// </summary>
    public bool VerifyInitialEnvelope(byte[] request308)
    {
        UnwrappedInitial fields = InspectInitialClientProof(request308);
        return fields.ZeroPaddingValid && fields.FixedTrailerValid;
    }

    public (byte[] prefix16, byte[] paddedMessage117, byte[] trailer11) InspectSecondClientProof(byte[] request184)
    {
        Packet packet = new Packet(request184);
        Guard.Operation(packet, Public.ClientProof, 144);
        if (!packet.Payload.AsSpan(133, 11).SequenceEqual(new byte[11])) throw new FormatException("Unexpected second proof padding.");
        return (packet.Payload.AsSpan(0, 16).ToArray(), packet.Payload.AsSpan(16, 117).ToArray(), packet.Payload.AsSpan(133, 11).ToArray());
    }
}
